def test_generate_cv_draft_uses_base_cv_and_evidence(tmp_path, monkeypatch):
    base_cv = tmp_path / "base_cv.md"
    base_cv.write_text("# Base CV\n\nVerified experience.", encoding="utf-8")
    monkeypatch.setenv("JOB_APP_BASE_CV_PATH", str(base_cv))
    tools = WorkflowTools()

    result = tools.generate_cv_draft(
        application_id="app-005",
        jd_content="Position: Sales Director",
        evidence_items=["Expanded a verified regional account."],
    )

    assert result["ok"] is True
    assert result["cv_draft"] == "Draft to be generated by frontend LLM."
    assert result["draft_version"] == 1
    assert "# Base CV" in result["system_prompt"]
    assert "Expanded a verified regional account." in result["system_prompt"]
    assert "Sales Director" in result["system_prompt"]


def test_generate_cv_draft_rejects_missing_context(workflow_tools):
    assert workflow_tools.generate_cv_draft("app-005", "", []) == {
        "ok": False,
        "error": "missing cv data",
    }


