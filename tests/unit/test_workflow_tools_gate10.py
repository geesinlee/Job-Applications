def test_answer_clarifying_questions_persists_only_nonempty_answers(
    workflow_tools,
    backend,
):
    result = workflow_tools.answer_clarifying_questions(
        application_id="app-003",
        answers={"leadership": "Led a team of five.", "cloud": "  ", "skip": None},
    )

    assert result == {
        "ok": True,
        "evidence_stored": 1,
        "next_action": "generate_cv_draft",
    }
    backend.save_application_evidence.assert_called_once()
    evidence = backend.save_application_evidence.call_args.args[0]
    assert isinstance(evidence, ApplicationScopedEvidence)
    assert evidence.application_id == "app-003"
    assert evidence.evidence_id == "app-003-leadership"
    assert evidence.response == "Led a team of five."
    assert evidence.source == "user_input"
    assert evidence.added_by_agent is False


def test_answer_clarifying_questions_rejects_empty_answers(workflow_tools):
    assert workflow_tools.answer_clarifying_questions("app-003", {}) == {
        "ok": False,
        "error": "answers dict is required",
    }


