@pytest.mark.parametrize(
    ("count", "stage", "progress"),
    [
        (0, "jd_analysis", 10),
        (1, "evidence_gathering", 30),
        (4, "cv_generation", 60),
        (8, "cv_refinement", 85),
    ],
)
def test_get_workflow_state_reflects_evidence_count(
    workflow_tools,
    backend,
    count,
    stage,
    progress,
):
    backend.get_evidence_by_application.return_value = [object()] * count

    result = workflow_tools.get_workflow_state("app-008")

    assert result["ok"] is True
    assert result["application_id"] == "app-008"
    assert result["evidence_count"] == count
    assert result["current_stage"] == stage
    assert result["progress_percent"] == progress


def test_get_workflow_state_falls_back_to_cv_evidence(backend):
    backend.get_evidence_by_application.return_value = []
    backend.get_evidence_by_cv_id.return_value = [object(), object()]
    tools = WorkflowTools(backend=backend)

    result = tools.get_workflow_state("app-009")

    assert result["evidence_count"] == 2
    backend.get_evidence_by_cv_id.assert_called_once_with("app-009")


def test_get_workflow_state_returns_structured_error(backend):
    backend.get_evidence_by_application.side_effect = RuntimeError("backend unavailable")
    tools = WorkflowTools(backend=backend)

    result = tools.get_workflow_state("app-010")

    assert result == {"ok": False, "error": "backend unavailable"}
